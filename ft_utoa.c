#include "ft_printf.h"

int	ft_utoa(unsigned int n)
{
	int		j;
	char	k;

	j = 0;
	k = (n % 10) + '0';
	if (n >= 10)
		j += ft_utoa(n / 10);
	j += write(1, &k, 1);
	return (j);
}
